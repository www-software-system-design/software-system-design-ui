import { act, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { Carousel } from './Carousel.js';
import { renderToString } from 'react-dom/server';
const labels = { previous: 'Previous', next: 'Next', pause: 'Pause', resume: 'Resume', indicators: 'Choose slide', carousel: 'carousel', slide: 'slide' };
const slides = [{ id: 'one', label: 'First', content: <a href='/one'>First action</a> }, { id: 'two', label: 'Second', content: <a href='/two'>Second action</a> }];
beforeEach(() => {
 vi.stubGlobal('matchMedia', vi.fn(() => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() })));
 vi.spyOn(HTMLElement.prototype, 'getBoundingClientRect').mockReturnValue(new DOMRect(0, 0, 300, 100));
});
afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals(); vi.restoreAllMocks(); });
it('does not advance while the document or carousel is hidden or outside the viewport', () => {
 vi.useFakeTimers();
 render(<Carousel label='Highlights' labels={labels} slides={slides} interval={1000} />);
 const hidden = vi.spyOn(document, 'hidden', 'get').mockReturnValue(true);
 act(() => vi.advanceTimersByTime(1000));
 expect(screen.getByRole('link', { name: 'First action' })).toBeVisible();
 hidden.mockReturnValue(false);
 const bounds = vi.spyOn(screen.getByRole('region'), 'getBoundingClientRect').mockReturnValue(new DOMRect(0, window.innerHeight + 100, 300, 100));
 act(() => vi.advanceTimersByTime(1000));
 expect(screen.getByRole('link', { name: 'First action' })).toBeVisible();
 bounds.mockReturnValue(new DOMRect());
 act(() => vi.advanceTimersByTime(1000));
 expect(screen.getByRole('link', { name: 'First action' })).toBeVisible();
});
it('renders deterministic initial HTML and retains local slide state', () => {
 const stateful = [{ id: 'draft', label: 'Draft', content: <input aria-label='Draft text' defaultValue='Original' /> }, slides[1]!];
 const html = renderToString(<Carousel label='SSR highlights' labels={labels} slides={stateful} />);
 expect(html).toContain('SSR highlights');
 expect(html).toContain('hidden=""');
 render(<Carousel label='Highlights' labels={labels} slides={stateful} />);
 fireEvent.change(screen.getByRole('textbox'), { target: { value: 'Edited' } });
 fireEvent.click(screen.getByRole('button', { name: 'Next' }));
 fireEvent.click(screen.getByRole('button', { name: 'Previous' }));
 expect(screen.getByRole('textbox')).toHaveValue('Edited');
});
it('suspends rotation on hover and consumer request and falls back after slide removal', () => {
 vi.useFakeTimers();
 const { rerender } = render(<Carousel label='Highlights' labels={labels} slides={slides} interval={1000} />);
 const region = screen.getByRole('region');
 fireEvent.mouseEnter(region);
 act(() => vi.advanceTimersByTime(2000));
 expect(screen.getByRole('link', { name: 'First action' })).toBeVisible();
 fireEvent.mouseLeave(region);
 act(() => vi.advanceTimersByTime(1000));
 expect(screen.getByRole('link', { name: 'Second action' })).toBeVisible();
 rerender(<Carousel label='Highlights' labels={labels} slides={slides} interval={1000} suspended />);
 act(() => vi.advanceTimersByTime(2000));
 expect(screen.getByRole('link', { name: 'Second action' })).toBeVisible();
 rerender(<Carousel label='Highlights' labels={labels} slides={slides.slice(0, 1)} interval={1000} />);
 expect(screen.getByRole('link', { name: 'First action' })).toBeVisible();
});
it('wraps slides and keeps inactive content inert', () => {
 render(<Carousel label='Highlights' labels={labels} slides={slides} />);
 expect(screen.getByRole('link', { name: 'First action' })).toBeVisible();
 expect(screen.getByText('Second action').closest('[inert]')).not.toBeNull();
 fireEvent.click(screen.getByRole('button', { name: 'Previous' }));
 expect(screen.getByRole('link', { name: 'Second action' })).toBeVisible();
 fireEvent.click(screen.getByRole('button', { name: 'Next' }));
 expect(screen.getByRole('link', { name: 'First action' })).toBeVisible();
 fireEvent.click(screen.getByRole('button', { name: 'Second' }));
 expect(screen.getByRole('button', { name: 'Second' })).toHaveAttribute('aria-current', 'true');
});
it('reports controlled selection and handles empty and single collections', () => {
 const change = vi.fn();
 const { rerender } = render(<Carousel label='Highlights' labels={labels} slides={slides} index={0} onIndexChange={change} />);
 fireEvent.click(screen.getByRole('button', { name: 'Next' }));
 expect(change).toHaveBeenCalledWith(1);
 expect(screen.getByRole('link', { name: 'First action' })).toBeVisible();
 rerender(<Carousel label='Highlights' labels={labels} slides={slides.slice(0, 1)} />);
 expect(screen.queryByRole('button', { name: 'Next' })).not.toBeInTheDocument();
 rerender(<Carousel label='Highlights' labels={labels} slides={[]} />);
 expect(screen.queryByRole('region')).not.toBeInTheDocument();
});
it('pauses rotation on focus until resumed and respects reduced motion', () => {
 vi.useFakeTimers();
 vi.stubGlobal('matchMedia', vi.fn(() => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() })));
 const { unmount } = render(<Carousel label='Highlights' labels={labels} slides={slides} interval={1000} />);
 act(() => vi.advanceTimersByTime(1000));
 expect(screen.getByRole('link', { name: 'Second action' })).toBeVisible();
 fireEvent.focus(screen.getByRole('link', { name: 'Second action' }));
 act(() => vi.advanceTimersByTime(2000));
 expect(screen.getByRole('link', { name: 'Second action' })).toBeVisible();
 fireEvent.click(screen.getByRole('button', { name: 'Resume' }));
 act(() => vi.advanceTimersByTime(1000));
 expect(screen.getByRole('link', { name: 'First action' })).toBeVisible();
 unmount();
 vi.stubGlobal('matchMedia', vi.fn(() => ({ matches: true, addEventListener: vi.fn(), removeEventListener: vi.fn() })));
 render(<Carousel label='Reduced' labels={labels} slides={slides} interval={1000} />);
 act(() => vi.advanceTimersByTime(3000));
 expect(screen.getByRole('link', { name: 'First action' })).toBeVisible();
});
